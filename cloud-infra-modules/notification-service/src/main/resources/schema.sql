-- ⚠️ 表归属: 下列 3 张表**不由本文件创建**, 它们由 system-module 的 Flyway 迁移管理
--    (db/migration/V1__init_schema.sql + V12__add_notification_preference_table.sql 等)。
--
--    本文件原先带着这些表的**过时副本**(如 sys_user 只有 7 列, 而 Flyway 已演进到 18 列)。
--    因为写的是 CREATE TABLE IF NOT EXISTS, 只要表不存在就会被这份副本抢先建出,
--    随后 Flyway 的 V1 会因 `column "user_id" of relation "sys_user" does not exist`
--    而失败, 并**连锁导致其后 10 个 migration 全部失败**。
--
--    实测复现(2026-10-05, 空库上先跑本文件再按序跑 Flyway):
--    17 个 migration 中 11 个失败。
--    生产当前未触发纯属 up.sh 的 FULL_SERVICES 顺序(system 在 notification 之前)
--    这个巧合 —— 顺序一变或单独在全新库上启动 notification 就会炸。
--
--    删掉副本而非保留, 是为了让表有**唯一管理者**; 保留一份过时定义等于
--    埋一颗只在特定顺序下才引爆的雷。留空占位注释以免后来者再抄一遍。
--
--    已核对运行库(cloud_infra)确认 Flyway 版本列完备:
--      sys_notification          12 列(含 dispatch_status/dispatch_attempts/channels)
--      sys_notification_preference 8 列(含 tenant_id)
--      sys_user                   18 列

-- 通知主表
CREATE TABLE IF NOT EXISTS sys_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    status SMALLINT NOT NULL DEFAULT 0,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_time TIMESTAMP,
    -- 分发状态: 0=待分发 1=分发中 2=已分发 3=分发失败
    -- 使本行自身充当发件箱记录, 支撑进程崩溃后的补扫重投
    dispatch_status SMALLINT NOT NULL DEFAULT 0,
    dispatch_attempts SMALLINT NOT NULL DEFAULT 0,
    -- 调用方请求的目标渠道 (逗号分隔的 channel_code, 如 'email,sms')。
    -- 分发在消费者侧异步执行, 原请求不可得, 故在此持久化以免分发器重算时丢失。
    channels VARCHAR(255)
);

-- 索引：用户+状态，用于快速查询未读通知
CREATE INDEX IF NOT EXISTS idx_notification_user_status ON sys_notification(user_id, status);

-- 索引：补扫待分发通知（dispatch_status + create_time 联合，按状态过滤后按时间取陈旧记录）
CREATE INDEX IF NOT EXISTS idx_notification_dispatch ON sys_notification(dispatch_status, create_time);

-- 渠道发送日志表
CREATE TABLE IF NOT EXISTS sys_notification_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL,
    channel_code VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    error_message TEXT,
    duration BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notification_log_nid ON sys_notification_log(notification_id);

-- 通知模板表
CREATE TABLE IF NOT EXISTS sys_notification_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_code VARCHAR(64) NOT NULL UNIQUE,
    title_template VARCHAR(255),
    content_template TEXT,
    recommended_channels VARCHAR(255),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 定时通知调度表
CREATE TABLE IF NOT EXISTS sys_notification_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    template_code VARCHAR(64),
    params_json TEXT,
    type VARCHAR(32) NOT NULL,
    schedule_time TIMESTAMP NOT NULL,
    processed BOOLEAN NOT NULL DEFAULT FALSE,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_schedule_time ON sys_notification_schedule(schedule_time, processed);

-- ⚠️ sys_notification_preference 由 system-module 的 Flyway 管理(V12), 不在此创建。
--    理由见文件开头「表归属」说明。

-- 设备告警规则表
CREATE TABLE IF NOT EXISTS sys_notification_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL,
    metric VARCHAR(64) NOT NULL,
    operator VARCHAR(8) NOT NULL,
    threshold DOUBLE PRECISION NOT NULL,
    template_code VARCHAR(64),
    target_user_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

--
--    本文件原先带着这些表的**过时副本**(如 sys_user 只有 7 列, 而 Flyway 已演进到 18 列)。
--    因为写的是 CREATE TABLE IF NOT EXISTS, 只要表不存在就会被这份副本抢先建出,
--    随后 Flyway 的 V1 会因 `column "user_id" of relation "sys_user" does not exist`
--    而失败, 并**连锁导致其后 10 个 migration 全部失败**。
--
--    实测复现(2026-10-05, 空库上先跑本文件再按序跑 Flyway):
--    17 个 migration 中 11 个失败。
--    生产当前未触发纯属 up.sh 的 FULL_SERVICES 顺序(system 在 notification 之前)
--    这个巧合 —— 顺序一变或单独在全新库上启动 notification 就会炸。
--
--    删掉副本而非保留, 是为了让表有**唯一管理者**; 保留一份过时定义等于
--    埋一颗只在特定顺序下才引爆的雷。留空占位注释以免后来者再抄一遍。
